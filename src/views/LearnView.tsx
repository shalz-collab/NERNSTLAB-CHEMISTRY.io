export function LearnView() {
  const { params, result, updateParams, selectPreset, setActivePage, motionMode } = useSimulation();
  const [selectedSymbol, setSelectedSymbol] = useState<SymbolKey>('Q');
  const [visibleStepCount, setVisibleStepCount] = useState<number>(1);

  const activeInfo = SYMBOLS.find((s) => s.key === selectedSymbol) ?? SYMBOLS[0];

  const getCurrentSimValue = (key: SymbolKey) => {
    if (!result.isValid) return '—';
    switch (key) {
      case 'E':
        return `${formatSigned(result.cellPotential, 4)} V`;
      case 'E0':
        return `${formatSigned(result.effectiveStandardPotential, 4)} V`;
      case 'R':
        return '8.3145 J/(mol·K)';
      case 'T':
        return `${formatNum(result.temperatureK, 2)} K`;
      case 'n':
        return `${params.electronsN} mol e⁻`;
      case 'F':
        return '96,485.33 C/mol';
      case 'Q':
        return formatScientific(result.effectiveQ, 3);
    }
  };

  const loadWorkedExampleIntoSim = () => {
    selectPreset('daniell');
    updateParams({
      anodeConc: 0.1,
      cathodeConc: 1.0,
      temperatureUnit: 'K',
      temperatureValue: 298.15,
      useManualQ: false,
    });
    setActivePage('simulator');
  };

  return (
    <div className="space-y-6">
      <SectionHeader
        title="Learn the Nernst Equation"
        subtitle="Interactive symbolic walkthrough, foundational electrochemistry principles, and a step-by-step worked Daniell cell example."
      />

      <LabCard className="p-6 space-y-5">
        <div className="flex flex-wrap items-baseline justify-between gap-2">
          <div>
            <h2 className="text-base font-bold text-[var(--text-primary)]">
              Interactive Equation Inspector
            </h2>
            <p className="text-xs text-[var(--text-muted)]">
              Click any variable or constant in the equation below to inspect its physical meaning and live value from your simulation.
            </p>
          </div>
          <span className="font-mono text-xs text-[var(--accent)]">
            25 °C form: E = E° − (0.05916 / n) log₁₀(Q)
          </span>
        </div>

        <div className="flex flex-wrap items-center justify-center gap-2 sm:gap-3 py-6 px-4 rounded-xl bg-[var(--bg-surface-elevated)] border border-[var(--border-hairline)] font-mono text-2xl sm:text-4xl text-[var(--text-primary)] select-none">
          {(['E', 'E0'] as SymbolKey[]).map((key, idx) => (
            <div key={key} className="inline-flex items-center gap-2">
              <button
                type="button"
                onClick={() => setSelectedSymbol(key)}
                className={`px-3 py-1.5 rounded-lg transition-all cursor-pointer ${
                  selectedSymbol === key
                    ? 'bg-[var(--accent)] text-[var(--accent-fg)] font-bold shadow-sm scale-105'
                    : 'hover:bg-[var(--bg-subtle)] text-[var(--text-primary)]'
                }`}
              >
                {key === 'E0' ? 'E°' : 'E'}
              </button>
              <span className="text-[var(--text-muted)]">{idx === 0 ? '=' : '−'}</span>
            </div>
          ))}

          <div className="inline-flex flex-col items-center mx-1">
            <div className="flex items-center gap-1 pb-1 border-b-2 border-[var(--text-primary)]">
              {(['R', 'T'] as SymbolKey[]).map((k) => (
                <button
                  key={k}
                  type="button"
                  onClick={() => setSelectedSymbol(k)}
                  className={`px-2 py-0.5 rounded-md text-xl sm:text-3xl transition-all cursor-pointer ${
                    selectedSymbol === k
                      ? 'bg-[var(--accent)] text-[var(--accent-fg)] font-bold'
                      : 'hover:bg-[var(--bg-subtle)]'
                  }`}
                >
                  {k}
                </button>
              ))}
            </div>
            <div className="flex items-center gap-1 pt-1">
              {(['n', 'F'] as SymbolKey[]).map((k) => (
                <button
                  key={k}
                  type="button"
                  onClick={() => setSelectedSymbol(k)}
                  className={`px-2 py-0.5 rounded-md text-xl sm:text-3xl transition-all cursor-pointer ${
                    selectedSymbol === k
                      ? 'bg-[var(--accent)] text-[var(--accent-fg)] font-bold'
                      : 'hover:bg-[var(--bg-subtle)]'
                  }`}
                >
                  {k}
                </button>
              ))}
            </div>
          </div>

          <span className="text-[var(--text-muted)] text-xl sm:text-3xl">ln</span>
          <button
            type="button"
            onClick={() => setSelectedSymbol('Q')}
            className={`px-3 py-1.5 rounded-lg transition-all cursor-pointer ${
              selectedSymbol === 'Q'
                ? 'bg-[var(--accent)] text-[var(--accent-fg)] font-bold shadow-sm scale-105'
                : 'hover:bg-[var(--bg-subtle)] text-[var(--text-primary)]'
            }`}
          >
            Q
          </button>
        </div>

        <motion.div
          key={activeInfo.key}
          initial={motionMode === 'reduced' ? false : { opacity: 0, y: 6 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.2 }}
          className="grid md:grid-cols-12 gap-5 p-5 rounded-xl bg-[var(--bg-surface-elevated)] border border-[var(--border-hairline)]"
        >
          <div className="md:col-span-3 flex flex-col justify-between border-b md:border-b-0 md:border-r border-[var(--border-hairline)] pb-3 md:pb-0 md:pr-4">
            <div>
              <div className="font-mono text-3xl font-bold text-[var(--accent)]">{activeInfo.glyph}</div>
              <div className="text-sm font-bold text-[var(--text-primary)] mt-1">{activeInfo.name}</div>
              <div className="font-mono text-xs text-[var(--text-muted)] mt-0.5">{activeInfo.units}</div>
            </div>
            <div className="pt-3 mt-3 border-t border-[var(--border-hairline)]">
              <div className="text-[11px] text-[var(--text-muted)]">Live Value in Simulator</div>
              <div className="font-mono text-sm font-semibold text-[var(--text-primary)]">
                {getCurrentSimValue(activeInfo.key)}
              </div>
            </div>
          </div>

          <div className="md:col-span-9 space-y-2.5 text-sm text-[var(--text-secondary)]">
            <div>
              <div className="text-xs font-semibold text-[var(--text-primary)]">Definition</div>
              <p className="mt-0.5 leading-relaxed">{activeInfo.definition}</p>
            </div>
            <div>
              <div className="text-xs font-semibold text-[var(--text-primary)]">Electrochemical Role</div>
              <p className="mt-0.5 leading-relaxed">{activeInfo.physicalRole}</p>
            </div>
          </div>
        </motion.div>
      </LabCard>

      <LabCard className="p-6 space-y-4">
        <div className="flex flex-wrap items-center justify-between gap-3 pb-4 border-b border-[var(--border-hairline)]">
          <div className="flex items-center gap-2.5">
            <BookOpen className="w-4 h-4 text-[var(--accent)]" />
            <div>
              <h2 className="text-base font-bold text-[var(--text-primary)]">
                Guided Worked Example: Non-Standard Daniell Cell
              </h2>
              <p className="text-xs text-[var(--text-muted)]">
                Reveal the derivation step-by-step, or load these exact values into the simulator.
              </p>
            </div>
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <LabButton
              variant="secondary"
              size="sm"
              onClick={() => setVisibleStepCount(1)}
              disabled={visibleStepCount === 1}
            >
              <RotateCcw className="w-3.5 h-3.5" />
              Reset Steps
            </LabButton>
            {visibleStepCount < WORKED_STEPS.length ? (
              <LabButton
                variant="primary"
                size="sm"
                onClick={() => setVisibleStepCount((c) => Math.min(c + 1, WORKED_STEPS.length))}
              >
                <ChevronRight className="w-4 h-4" />
                Reveal Step {visibleStepCount + 1}
              </LabButton>
            ) : (
              <LabButton variant="primary" size="sm" onClick={loadWorkedExampleIntoSim}>
                Load into Simulator
                <ArrowRight className="w-3.5 h-3.5" />
              </LabButton>
            )}
            {visibleStepCount < WORKED_STEPS.length && (
              <LabButton
                variant="ghost"
                size="sm"
                onClick={() => setVisibleStepCount(WORKED_STEPS.length)}
              >
                <Play className="w-3.5 h-3.5" />
                Show All
              </LabButton>
            )}
          </div>
        </div>

        <div className="space-y-3">
          {WORKED_STEPS.slice(0, visibleStepCount).map((s, idx) => (
            <motion.div
              key={s.title}
              initial={motionMode === 'reduced' ? false : { opacity: 0, y: 8 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ duration: 0.22 }}
              className={`p-4 rounded-xl border ${
                idx === WORKED_STEPS.length - 1
                  ? 'bg-[var(--accent-soft)] border-[var(--accent-border)]'
                  : 'bg-[var(--bg-surface-elevated)] border-[var(--border-hairline)]'
              }`}
            >
              <div className="text-xs font-bold text-[var(--text-primary)] mb-1.5">{s.title}</div>
              <div className="space-y-1 font-mono text-xs text-[var(--text-secondary)]">
                {s.lines.map((line) => (
                  <div key={line}>{line}</div>
                ))}
              </div>
            </motion.div>
          ))}
        </div>
      </LabCard>

      <div className="grid md:grid-cols-2 gap-4">
        {CONCEPTS.map((c) => (
          <LabCard key={c.title} className="p-5 space-y-2">
            <h3 className="text-sm font-bold text-[var(--text-primary)]">{c.title}</h3>
            <p className="text-xs leading-relaxed text-[var(--text-secondary)]">{c.body}</p>
          </LabCard>
        ))}
      </div>
    </div>
  );
}
